#!/usr/bin/env python3
"""
Concatène les feuilles de style modulaires en un seul fichier main.css.
Exécution:
    python scripts/build_css.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STYLES_DIR = ROOT / "website-morpion" / "static" / "styles"
OUTPUT_FILE = STYLES_DIR / "main.css"

CSS_SOURCES = [
    # === CORE (base system) ===
    "base.css",
    
    # === UTILITIES ===
    "utilities.css",
    
    # === LAYOUT ===
    "layout.css",
    
    # === COMPONENTS ===
    "components/badges.css",
    "components/stats.css",
    "components/charts.css",  # NEW: Reusable charts
    "components/team-card.css",  # NEW: Reusable team cards
    "components/buttons.css",
    "components/forms.css",
    "components/alerts.css",
    "components/hero.css",
    "components/empty-state.css",
    "components/confirmation-dialog.css",
    "components/design-system.css",
    "components/game-info-header.css",
    "components/game-grid.css",
    "components/game-logs.css",
    "components/deck-status.css",
    "components/footer.css",
    "components/morpion-card.css",
    "components/morpion-selector.css",
    "components/position-selector.css",
    "components/game-created-box.css",
    "components/duration-compare.css",
    
    # === PAGES ===
    "pages/team_create.css",
    "pages/team_list.css",
    "pages/morpion_create.css",
    "pages/game_setup.css",
    "pages/game_play.css",
    "pages/data_diagram.css",
    "pages/stats_advanced.css",
    "pages/documentation.css",
]


def main():
    parts = [
        "/* Auto-generated by scripts/build_css.py - do not edit manually. */\n"
    ]
    for rel_path in CSS_SOURCES:
        source = STYLES_DIR / rel_path
        if not source.exists():
            raise FileNotFoundError(f"CSS source missing: {source}")
        parts.append(f"\n/* === {rel_path} === */\n")
        parts.append(source.read_text())
    OUTPUT_FILE.write_text("".join(parts))
    print(f"Wrote {OUTPUT_FILE.relative_to(ROOT)} with {len(CSS_SOURCES)} sources.")


if __name__ == "__main__":
    main()
